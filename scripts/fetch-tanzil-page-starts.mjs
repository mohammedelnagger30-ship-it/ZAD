import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://tanzil.net/res/text/metadata/quran-data.xml';
const OUTPUT_PATH = fileURLToPath(new URL('../src/data/mushafPageStarts.ts', import.meta.url));

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`Tanzil metadata request failed: HTTP ${response.status}`);

const xml = await response.text();
const root = xml.match(/<quran\b([^>]*)>/)?.[1];
if (!root || !/\blicense="cc-by"/i.test(root)) {
  throw new Error('Tanzil metadata does not declare the expected CC BY license.');
}

const sourceSurahs = JSON.parse(
  await readFile(new URL('../src/data/quran-full.json', import.meta.url), 'utf8'),
);
const surahCounts = Object.fromEntries(
  Object.entries(sourceSurahs).map(([surahId, ayahs]) => [Number(surahId), ayahs.length]),
);
const starts = [...xml.matchAll(/<page\b([^>]*)\/>/g)].map(([, attributes]) => {
  const index = Number(attributes.match(/\bindex="(\d+)"/)?.[1]);
  const surahId = Number(attributes.match(/\bsura="(\d+)"/)?.[1]);
  const ayahNumber = Number(attributes.match(/\baya="(\d+)"/)?.[1]);
  if (![index, surahId, ayahNumber].every(Number.isInteger)) {
    throw new Error(`Malformed page metadata: ${attributes}`);
  }
  return { index, surahId, ayahNumber };
});

if (starts.length !== 604) throw new Error(`Expected 604 page starts, received ${starts.length}.`);
if (starts[0].index !== 1 || starts[0].surahId !== 1 || starts[0].ayahNumber !== 1) {
  throw new Error('The first page must start at Al-Fatihah 1:1.');
}

let previousSurah = 0;
let previousAyah = 0;
for (const [offset, start] of starts.entries()) {
  if (start.index !== offset + 1) throw new Error(`Unexpected page index ${start.index}.`);
  if (!surahCounts[start.surahId] || start.ayahNumber < 1 || start.ayahNumber > surahCounts[start.surahId]) {
    throw new Error(`Page ${start.index} starts at an unknown ayah ${start.surahId}:${start.ayahNumber}.`);
  }
  if (start.surahId < previousSurah || (start.surahId === previousSurah && start.ayahNumber <= previousAyah)) {
    throw new Error(`Page starts are not in Quran order at page ${start.index}.`);
  }
  previousSurah = start.surahId;
  previousAyah = start.ayahNumber;
}

const rows = starts.map(({ surahId, ayahNumber }) => `  [${surahId}, ${ayahNumber}],`);
const output = `/**
 * Page-start ayahs for the 604-page Madani mushaf.
 *
 * Source: Tanzil Quran Metadata v1.0, https://tanzil.net/res/text/metadata/quran-data.xml
 * Copyright (C) 2008-2009 Tanzil.info; license: Creative Commons Attribution 3.0.
 * Generated by scripts/fetch-tanzil-page-starts.mjs; do not edit by hand.
 */
export const PRINTED_PAGE_STARTS: readonly (readonly [surahId: number, ayahNumber: number])[] = [
${rows.join('\n')}
];
`;

await writeFile(OUTPUT_PATH, output, 'utf8');
console.log(`Wrote ${starts.length} Tanzil page starts to ${OUTPUT_PATH}.`);
