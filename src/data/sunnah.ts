/**
 * The narration library behind «سنن عن النبي ﷺ».
 *
 * Each entry is a practice the ﷺ kept, with the narration that carries it. The fields
 * are deliberately layered so a card can be read at three depths without leaving the page:
 *
 *   text     — the Sunnah itself: what he did, stated plainly.
 *   mawqif   — the occasion it happened in, when one is known. A bare rule is easy to
 *              skim past; the same rule with the room it was said in is not, so the
 *              incidents the request asked for live here.
 *   evidence — the hadith, quoted, with its book. Tapping it opens the hadith screen on
 *              that quote; see hadithSearchQuery in SunnahScreen for how a fragment
 *              becomes a query.
 *   benefit  — what the practice yields — the reason behind the rule.
 *   note     — the ruling, kept short so it never buries the practice itself.
 *   grade    — the standing of the narration, on the badge at the card's corner.
 *
 * Nothing here is paraphrased scripture: `evidence` carries the wording as the books
 * give it, and `mawqif`/`benefit` are context written around it, not quotations.
 */

export interface SunnahItem {
  title: string;
  text: string;
  /** The occasion or setting the practice is reported in, when one is known. */
  mawqif?: string;
  evidence: string;
  /** The fruit of the practice — why the rule is worth keeping. */
  benefit?: string;
  note?: string;
  grade?: string;
}

export interface SunnahCategory {
  id: string;
  title: string;
  subtitle: string;
  /** A lucide component; the card tints its tile with `color`. */
  icon: string;
  color: string;
  items: SunnahItem[];
}

