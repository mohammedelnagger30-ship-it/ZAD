function quranPassage(surahId: number, fromAyah: number, toAyah = fromAyah) {
  const surah = SURAHS.find((item) => item.id === surahId);
  const ayahs = getAyahs(surahId, fromAyah, toAyah);
  if (!surah || ayahs.length !== toAyah - fromAyah + 1) {
    throw new Error(`تعذّر تحميل نص الدعاء القرآني ${surahId}:${fromAyah}-${toAyah}.`);
  }

  const ayahLabel = fromAyah === toAyah
    ? `الآية ${toArabicNumber(fromAyah)}`
    : `الآيات ${toArabicNumber(fromAyah)}-${toArabicNumber(toAyah)}`;
  return {
    text: ayahs.map((ayah) => ayah.text).join(' '),
    reference: `سورة ${surah.name} — ${ayahLabel}`,
  };
}

function quranSurah(surahId: number) {
  const surah = SURAHS.find((item) => item.id === surahId);
  const ayahs = getAyahs(surahId);
  if (!surah || ayahs.length !== surah.ayahCount) {
    throw new Error(`تعذّر تحميل نص سورة ${surahId} كاملاً.`);
  }
  return { name: surah.name, text: ayahs.map((ayah) => ayah.text).join(' ') };
}

