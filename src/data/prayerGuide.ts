/**
 * فقه الصلاة — page content.
 *
 * Every `text` below is a contiguous verbatim excerpt of the source it cites: hadith
 * excerpts come from the locally cached sunnah.com texts (`.cache/content/hadith-ara-*.json`,
 * same store the hadith library and الأذكار use), and Quran excerpts come from the bundled
 * Uthmani text (`quran-full.json`). Nothing here is written from memory — see SOURCES.md §7.
 *
 * `source` uses Arabic-Indic numerals; `grade` is only present where a grader's own wording
 * supports it (stated in the hadith text itself or in the grading column of the source).
 */

export interface PrayerGuideItem {
  /** stable id, pinned by scripts/check-content.ts */
  id: string;
  /** short section-facing label (UI wording, not a quotation) */
  title: string;
  /** one neutral line describing the item, never a new ruling */
  hint: string;
  /** the verbatim excerpt */
  text: string;
  /** collection + Arabic-Indic hadith number, or surah + ayah for Quran */
  source: string;
  /** optional grading suffix, only where sourced */
  grade?: string;
}

export type PrayerPostureId =
  | 'takbir'
  | 'qiyam'
  | 'ruku'
  | 'raf'
  | 'sujud'
  | 'jalsa'
  | 'tashahhud';

export interface PrayerGuideStep extends PrayerGuideItem {
  posture: PrayerPostureId;
}

